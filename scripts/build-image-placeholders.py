# Rebuilds src/lib/image-placeholders.ts: a 20px-wide preview of every .webp
# photo in public/, shown blurred while the full image loads.
#
#   python3 scripts/build-image-placeholders.py        (from the project root, needs Pillow)
import base64, io, os
from PIL import Image

PUBLIC, OUT, SKIP = "public", "src/lib/image-placeholders.ts", {"medcare3d.webp"}

rows = []
for name in sorted(os.listdir(PUBLIC)):
    if not name.endswith(".webp") or name in SKIP:
        continue
    image = Image.open(os.path.join(PUBLIC, name)).convert("RGB")
    width = 20
    height = max(1, round(image.height * width / image.width))
    buffer = io.BytesIO()
    image.resize((width, height)).save(buffer, "WEBP", quality=35)
    rows.append((name, base64.b64encode(buffer.getvalue()).decode()))

with open(OUT, "w") as out:
    out.write("// AUTO-GENERATED by scripts/build-image-placeholders.py: 20px-wide previews of\n")
    out.write("// the photos in public/, shown blurred while the full image loads.\n")
    out.write("// Run the script again whenever a photo is added or replaced.\n")
    out.write("export const IMAGE_PLACEHOLDERS: Record<string, string> = {\n")
    for name, data in rows:
        out.write(f'  "/{name}": "data:image/webp;base64,{data}",\n')
    out.write("};\n")
print(f"{len(rows)} previews written to {OUT}")
